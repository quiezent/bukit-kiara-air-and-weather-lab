"""Build WeatherDashboard/WebPage.h (the device's web page) from WeatherDashboard/web/index.html.

    python tools/build_web.py           # regenerate WebPage.h
    python tools/build_web.py --check   # exit 1 if the committed WebPage.h does not match index.html

The minifier only removes things that cannot change behaviour:
  HTML: comments, indentation, blank lines.
  CSS:  comments, indentation, blank lines.
  JS:   indentation, blank lines, and comments that stand on their own line.
It keeps every newline between JavaScript statements and never rewrites code.

The page therefore has to follow three rules, and the build stops if it breaks one:
no template literals or backslash line continuations in the script, and no
<pre> or <textarea> anywhere, because stripping indentation would change them.

The gzip stream is written with mtime 0, so the same page and the same zlib give
the same bytes. --check passes when WebPage.h is byte-identical to a fresh build,
or when its embedded stream decompresses to exactly the freshly minified page
(another zlib build can compress the same page differently); it fails otherwise.
"""
import argparse
import gzip
import re
import sys
from pathlib import Path

PACKAGE = Path(__file__).resolve().parents[1]
FIRMWARE = PACKAGE / "WeatherDashboard"
SOURCE = FIRMWARE / "web" / "index.html"
TARGET = FIRMWARE / "WebPage.h"
SIZE_LIMIT = 40_000  # bytes of gzip output
# Kept identical to the upstream generator's first line so that the published
# WebPage.h reproduces byte for byte.
GENERATED_BY = "// Generated by build_web.py from web/index.html. Do not edit by hand."

BLOCK = re.compile(r"(<style\b[^>]*>)(.*?)(</style>)|(<script\b[^>]*>)(.*?)(</script>)", re.S | re.I)


class PageError(ValueError):
    pass


def kept_lines(text):
    return "\n".join(line for line in (raw.strip() for raw in text.splitlines()) if line)


def minify_html(text):
    if re.search(r"<(pre|textarea)\b", text, re.I):
        raise PageError("<pre> and <textarea> are not supported by this minifier")
    return kept_lines(re.sub(r"<!--.*?-->", "", text, flags=re.S))


def minify_css(text):
    if re.search(r"""["'][^"'\n]*/\*""", text):
        raise PageError("a CSS string contains '/*'")
    return kept_lines(re.sub(r"/\*.*?\*/", "", text, flags=re.S))


def minify_js(text):
    if "`" in text:
        raise PageError("the script contains a template literal")
    output = []
    in_comment = False
    for raw in text.splitlines():
        if raw.rstrip().endswith("\\"):
            raise PageError(f"the script has a line continuation: {raw.strip()[:60]}")
        line = raw.strip()
        if in_comment:
            if "*/" in line:
                if line.split("*/", 1)[1].strip():
                    raise PageError(f"code follows a block comment: {line[:60]}")
                in_comment = False
            continue
        if not line or line.startswith("//"):
            continue
        if line.startswith("/*"):
            if "*/" not in line:
                in_comment = True
            elif line.split("*/", 1)[1].strip():
                raise PageError(f"code follows a block comment: {line[:60]}")
            continue
        output.append(line)
    return "\n".join(output)


def minify(page):
    parts = []
    position = 0
    for match in BLOCK.finditer(page):
        parts.append(minify_html(page[position:match.start()]))
        if match.group(1):
            parts.append(match.group(1) + "\n" + minify_css(match.group(2)) + "\n" + match.group(3))
        else:
            parts.append(match.group(4) + "\n" + minify_js(match.group(5)) + "\n" + match.group(6))
        position = match.end()
    parts.append(minify_html(page[position:]))
    return "\n".join(part for part in parts if part) + "\n"


def header(data):
    rows = [
        "  " + ",".join(f"0x{byte:02x}" for byte in data[index:index + 20]) + ","
        for index in range(0, len(data), 20)
    ]
    return "\n".join([
        GENERATED_BY,
        "#pragma once",
        "#include <Arduino.h>",
        "",
        "static const uint8_t kWebPageGz[] PROGMEM = {",
        *rows,
        "};",
        f"static constexpr size_t kWebPageGzSize = {len(data)};",
        "",
    ])


def build(page):
    """Return (minified page bytes, gzip bytes, header text) for an index.html string."""
    minified = minify(page).encode("utf-8")
    data = gzip.compress(minified, compresslevel=9, mtime=0)
    if gzip.decompress(data) != minified:
        raise PageError("gzip round trip failed")
    if len(data) >= SIZE_LIMIT:
        raise PageError(f"gzipped page is {len(data)} bytes; the limit is {SIZE_LIMIT}")
    return minified, data, header(data)


def embedded_payload(text):
    """The gzip bytes a WebPage.h embeds, or None when its layout is not this generator's."""
    match = re.search(r"kWebPageGz\[\] PROGMEM = \{\n(.*?)\};\nstatic constexpr size_t kWebPageGzSize = (\d+);",
                      text, re.S)
    if not match:
        return None
    data = bytes(int(value, 16) for value in re.findall(r"0x([0-9a-f]{2})", match.group(1)))
    if len(data) != int(match.group(2)) or header(data) != text:
        return None
    return data


def check(source, target):
    """0 when target matches source (byte-identical or same page); 1 otherwise. Prints the verdict."""
    minified, _, expected = build(source.read_text(encoding="utf-8"))
    if not target.is_file():
        print(f"build_web: {target.name} is missing; run python tools/build_web.py")
        return 1
    committed = target.read_bytes()
    if committed == expected.encode("ascii"):
        print(f"build_web: {target.name} is byte-identical to a fresh build of {source.name}")
        return 0
    payload = embedded_payload(committed.decode("ascii", errors="replace"))
    try:
        same_page = payload is not None and gzip.decompress(payload) == minified
    except (OSError, EOFError):
        same_page = False
    if same_page:
        print(f"build_web: {target.name} embeds exactly the minified {source.name}; "
              "its gzip stream differs from this Python's zlib output")
        return 0
    print(f"build_web: {target.name} does not match {source.name}; run python tools/build_web.py")
    return 1


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="Compare the committed WebPage.h; write nothing")
    args = parser.parse_args(argv)
    try:
        if args.check:
            return check(SOURCE, TARGET)
        page = SOURCE.read_text(encoding="utf-8")
        minified, data, text = build(page)
    except PageError as error:
        print(f"build_web: {error}", file=sys.stderr)
        return 1
    with TARGET.open("w", encoding="ascii", newline="\n") as out:
        out.write(text)
    print(f"{SOURCE.name}: {len(page.encode('utf-8'))} bytes, minified {len(minified)}, gzip {len(data)}")
    print(f"wrote {TARGET.relative_to(PACKAGE).as_posix()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
